#!/usr/bin/env bun
/**
 * Generates the two language-server tables from the canonical registry
 * `lsp/servers.json`:
 *
 *   - `packages/coding-agent/src/lsp/servers.generated.ts` — the coding-agent's
 *     builtin servers, keyed by server name.
 *   - `termide/crates/config/src/lsp_servers_generated.rs` — termide's builtin
 *     servers, keyed by the editor language ids `LspManager::detect_language`
 *     returns (the canonical entry's `languages` field).
 *
 * The canonical file is the single source of truth for both consumers. Every
 * entry carries `command`, `args`, `fileTypes` and `rootMarkers`; `candidates`
 * is an ordered alternative list (first command that resolves on PATH wins) and
 * `languages` maps the entry into termide's language-keyed table only, so it is
 * stripped from the TypeScript output.
 *
 * Usage:
 *   bun scripts/gen-lsp-servers.ts            # write both generated files
 *   bun scripts/check-lsp-servers.ts          # assert they are up to date
 */
import * as path from "node:path";

export const REPO_ROOT = path.join(import.meta.dir, "..");
export const CANONICAL_PATH = path.join(REPO_ROOT, "lsp", "servers.json");
export const TS_OUTPUT_PATH = path.join(REPO_ROOT, "packages", "coding-agent", "src", "lsp", "servers.generated.ts");
export const RUST_OUTPUT_PATH = path.join(REPO_ROOT, "termide", "crates", "config", "src", "lsp_servers_generated.rs");

export interface LspCandidate {
	command: string;
	args?: string[];
}

export interface CanonicalServer {
	command: string;
	args?: string[];
	fileTypes: string[];
	rootMarkers: string[];
	/** Editor language ids termide serves with this entry. Generation metadata, not a client option. */
	languages?: string[];
	/** Ordered alternatives; the first whose command resolves on PATH wins. */
	candidates?: LspCandidate[];
	initOptions?: Record<string, unknown>;
	settings?: Record<string, unknown>;
	isLinter?: boolean;
	languageId?: string;
	warmupTimeoutMs?: number;
	capabilities?: Record<string, unknown>;
	[key: string]: unknown;
}

export interface CanonicalRegistry {
	servers: Record<string, CanonicalServer>;
}

const HEADER = "Generated by scripts/gen-lsp-servers.ts from lsp/servers.json. Do not edit by hand.";

/** Keys written by the TypeScript generator, in output order. */
const TS_FIELDS = [
	"command",
	"args",
	"fileTypes",
	"rootMarkers",
	"candidates",
	"initOptions",
	"settings",
	"isLinter",
	"languageId",
	"warmupTimeoutMs",
	"capabilities",
] as const;

function fail(message: string): never {
	throw new Error(`${path.relative(REPO_ROOT, CANONICAL_PATH)}: ${message}`);
}

function assertStringArray(value: unknown, where: string, allowEmpty = false): string[] {
	if (!Array.isArray(value) || value.some(entry => typeof entry !== "string" || entry.length === 0)) {
		fail(`${where} must be an array of non-empty strings`);
	}
	if (!allowEmpty && value.length === 0) fail(`${where} must not be empty`);
	return value as string[];
}

function assertCandidates(value: unknown, where: string): LspCandidate[] {
	if (!Array.isArray(value) || value.length === 0) fail(`${where} must be a non-empty array`);
	return value.map((entry, index) => {
		if (typeof entry !== "object" || entry === null || Array.isArray(entry)) {
			fail(`${where}[${index}] must be an object`);
		}
		const candidate = entry as Record<string, unknown>;
		const command = candidate.command;
		if (typeof command !== "string" || command.length === 0) {
			fail(`${where}[${index}].command must be a non-empty string`);
		}
		const args =
			candidate.args === undefined ? undefined : assertStringArray(candidate.args, `${where}[${index}].args`, true);
		return { command, ...(args === undefined ? {} : { args }) };
	});
}

/** Parse and validate the canonical registry. Generation refuses malformed input. */
export async function loadCanonical(): Promise<CanonicalRegistry> {
	const raw = (await Bun.file(CANONICAL_PATH).json()) as unknown;
	if (typeof raw !== "object" || raw === null || Array.isArray(raw)) fail("top level must be an object");
	const servers = (raw as Record<string, unknown>).servers;
	if (typeof servers !== "object" || servers === null || Array.isArray(servers)) {
		fail("must have a `servers` object");
	}
	const languages = new Map<string, string>();
	const result: Record<string, CanonicalServer> = {};
	for (const [key, value] of Object.entries(servers as Record<string, unknown>)) {
		if (typeof value !== "object" || value === null || Array.isArray(value)) fail(`servers.${key} must be an object`);
		const server = value as Record<string, unknown>;
		if (typeof server.command !== "string" || server.command.length === 0) {
			fail(`servers.${key}.command must be a non-empty string`);
		}
		const entry: CanonicalServer = {
			command: server.command,
			...(server.args === undefined ? {} : { args: assertStringArray(server.args, `servers.${key}.args`, true) }),
			fileTypes: assertStringArray(server.fileTypes, `servers.${key}.fileTypes`),
			rootMarkers: assertStringArray(server.rootMarkers, `servers.${key}.rootMarkers`),
		};
		if (server.candidates !== undefined) {
			entry.candidates = assertCandidates(server.candidates, `servers.${key}.candidates`);
		}
		if (server.languages !== undefined) {
			entry.languages = assertStringArray(server.languages, `servers.${key}.languages`);
			for (const language of entry.languages) {
				const owner = languages.get(language);
				if (owner) fail(`language "${language}" is claimed by both "${owner}" and "${key}"`);
				languages.set(language, key);
			}
		}
		for (const field of ["initOptions", "settings", "capabilities"] as const) {
			const value = server[field];
			if (value !== undefined && (typeof value !== "object" || value === null || Array.isArray(value))) {
				fail(`servers.${key}.${field} must be an object`);
			}
		}
		if (server.isLinter !== undefined && typeof server.isLinter !== "boolean") {
			fail(`servers.${key}.isLinter must be a boolean`);
		}
		if (server.warmupTimeoutMs !== undefined && typeof server.warmupTimeoutMs !== "number") {
			fail(`servers.${key}.warmupTimeoutMs must be a number`);
		}
		// Carry every client-facing field through unchanged; `languages` was
		// copied above and is generation metadata for the Rust table only.
		for (const field of TS_FIELDS) {
			if (server[field] !== undefined) entry[field] = server[field];
		}
		result[key] = entry;
	}
	return { servers: result };
}

function sortedKeys(servers: Record<string, CanonicalServer>): string[] {
	return Object.keys(servers).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/** TypeScript table: canonical entries keyed by server name, without generation metadata. */
function typescriptServers(registry: CanonicalRegistry): Record<string, Record<string, unknown>> {
	const output: Record<string, Record<string, unknown>> = {};
	for (const key of sortedKeys(registry.servers)) {
		const source = registry.servers[key];
		const entry: Record<string, unknown> = {};
		for (const field of TS_FIELDS) {
			if (source[field] !== undefined) entry[field] = source[field];
		}
		output[key] = entry;
	}
	return output;
}

/** Render the coding-agent module. Deterministic: sorted keys, embedded JSON, no formatting dependency. */
export function renderTypescript(registry: CanonicalRegistry): string {
	const servers = typescriptServers(registry);
	const json = JSON.stringify(servers, null, "\t");
	if (json.includes("`") || json.includes("${")) {
		throw new Error(
			"lsp/servers.json serializes to a backtick or template interpolation; the generated module embeds JSON in a template literal",
		);
	}
	return [
		`// ${HEADER}`,
		"",
		'import type { ServerConfig } from "./types";',
		"",
		"/**",
		" * Builtin LSP servers, keyed by server name, exactly as `lsp/servers.json`",
		" * declares them. `candidates` lists the alternatives in preference order; the",
		" * first one that resolves on PATH is the command that runs.",
		" */",
		"export const LSP_SERVERS: Record<string, ServerConfig> = JSON.parse(",
		`\tString.raw\`${json}\`,`,
		");",
		"",
	].join("\n");
}

function rustString(value: string): string {
	let out = '"';
	for (const char of value) {
		switch (char) {
			case "\\":
				out += "\\\\";
				break;
			case '"':
				out += '\\"';
				break;
			case "\n":
				out += "\\n";
				break;
			case "\r":
				out += "\\r";
				break;
			case "\t":
				out += "\\t";
				break;
			default: {
				const code = char.codePointAt(0) ?? 0;
				out += code < 0x20 ? `\\u{${code.toString(16)}}` : char;
			}
		}
	}
	return `${out}"`;
}

function rustVec(values: readonly string[]): string {
	return `vec![${values.map(value => `${rustString(value)}.to_string()`).join(", ")}]`;
}

function rustCandidates(candidates: readonly LspCandidate[]): string {
	const lines = ["vec!["];
	for (const candidate of candidates) {
		lines.push("                LspCandidate {");
		lines.push(`                    command: ${rustString(candidate.command)}.to_string(),`);
		lines.push(`                    args: ${rustVec(candidate.args ?? [])},`);
		lines.push("                },");
	}
	lines.push("            ]");
	return lines.join("\n");
}

/** Render termide's language-keyed table. Deterministic: languages sorted, one insert per language. */
export function renderRust(registry: CanonicalRegistry): string {
	const entries: Array<[string, CanonicalServer]> = [];
	for (const key of sortedKeys(registry.servers)) {
		const server = registry.servers[key];
		for (const language of server.languages ?? []) entries.push([language, server]);
	}
	entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

	const lines = [
		`// ${HEADER}`,
		"//",
		"// Termide keys its LSP table by editor language id; `lsp/servers.json` keys",
		"// servers by name and lists the language ids each entry serves (`languages`).",
		"// The command/args pair mirrors the first candidate; `candidates` is what",
		"// selection actually walks.",
		"use std::collections::HashMap;",
		"",
		"use crate::settings::{LspCandidate, LspServerSettings};",
		"",
		"/// The builtin LSP servers, keyed by the language ids `LspManager::detect_language` returns.",
		"#[rustfmt::skip]",
		"pub fn builtin_lsp_servers() -> HashMap<String, LspServerSettings> {",
		"    let mut servers = HashMap::new();",
	];
	for (const [language, server] of entries) {
		lines.push("    servers.insert(");
		lines.push(`        ${rustString(language)}.to_string(),`);
		lines.push("        LspServerSettings {");
		lines.push(`            command: ${rustString(server.command)}.to_string(),`);
		lines.push(`            args: ${rustVec(server.args ?? [])},`);
		lines.push(`            root_markers: ${rustVec(server.rootMarkers)},`);
		lines.push(`            candidates: ${rustCandidates(server.candidates ?? [])},`);
		lines.push("        },");
		lines.push("    );");
	}
	lines.push("    servers", "}", "");
	// Server key -> language ids, so the shared `~/.zeta/lsp.json` override can
	// name a server key (the coding-agent's key space) and still apply here.
	const serverLanguages = sortedKeys(registry.servers)
		.filter(key => (registry.servers[key].languages?.length ?? 0) > 0)
		.map(key => [key, registry.servers[key].languages ?? []] as const);
	lines.push("/// Canonical server keys and the language ids each one serves.");
	lines.push("#[rustfmt::skip]");
	lines.push("pub fn builtin_lsp_server_languages() -> HashMap<&'static str, &'static [&'static str]> {");
	lines.push("    HashMap::from([");
	for (const [key, languages] of serverLanguages) {
		const values = languages.map(language => rustString(language)).join(", ");
		lines.push(`        (${rustString(key)}, &[${values}] as &[&str]),`);
	}
	lines.push("    ])");
	lines.push("}", "");
	return lines.join("\n");
}

export async function renderAll(): Promise<{ typescript: string; rust: string }> {
	const registry = await loadCanonical();
	return { typescript: renderTypescript(registry), rust: renderRust(registry) };
}

if (import.meta.main) {
	const rendered = await renderAll();
	await Bun.write(TS_OUTPUT_PATH, rendered.typescript);
	await Bun.write(RUST_OUTPUT_PATH, rendered.rust);
	const registry = await loadCanonical();
	console.log(
		`lsp servers: ${Object.keys(registry.servers).length} builtins -> ${path.relative(REPO_ROOT, TS_OUTPUT_PATH)}, ${path.relative(REPO_ROOT, RUST_OUTPUT_PATH)}`,
	);
}
