import { ALIAS_PREFIX, STATIC_CONSTANTS, STATIC_PREFIX, aliasColorTokens, legacyColorTokens, staticColorTokens } from "./tokens";
import type { Theme } from "./types";

/**
 * Renders the checked-in fallback sheet (`styles/themes/zeta-static.css`).
 *
 * The sheet carries the same three colour layers as the runtime generator, for
 * the two default themes, so the very first frame is fully themed before the
 * inline bootstrap script or React hydration runs:
 *
 *   `:root`                 L1 statics + L2 aliases + L3 bridge of the default
 *                           light theme
 *   `[data-theme="dark"]`   the single dark override table: the complete L1
 *                           layer of the default dark theme
 *
 * L2 is variant-invariant by construction (every alias is a `var()` reference
 * to an L1 token), so it is declared once instead of being duplicated into the
 * dark table — a second copy would only create a second place to edit.
 *
 * The file is generated by `node scripts/gen-theme-static.mjs` and asserted
 * against this renderer by `lib/theme/theme-system.test.mjs`.
 */
export function renderStaticThemeSheet(light: Theme, dark: Theme): string {
  const lines: string[] = [
    "/*",
    " * GENERATED FILE — do not edit by hand.",
    " * Regenerate with: `node scripts/gen-theme-static.mjs` (from web-ui/).",
    " * Source of truth: lib/theme/tokens.ts + lib/theme/themes/*.json.",
    " *",
    " * Fallback colour layers for the first frame, before the inline theme",
    " * bootstrap script and React hydration apply the selected preset:",
    " *   L1 --zeta-static-*   raw palette (only place colour literals may live)",
    " *   L2 --zeta-alias-*    semantic aliases — what feature CSS/TSX consumes",
    " *   L3 --<name>          compat bridge for the unprefixed legacy names",
    " *",
    " * `[data-theme=\"dark\"]` is the single dark override table and holds the",
    " * whole L1 layer for the default dark theme. L2 is not repeated there: every",
    " * alias is a var() reference to L1, so it is variant-invariant by design.",
    " */",
    "",
    ":root {",
    `  /* L1 — raw palette (${light.metadata.id}) */`,
  ];

  for (const [name, value] of [...staticColorTokens(light), ...STATIC_CONSTANTS]) {
    lines.push(`  ${STATIC_PREFIX}${name}: ${value};`);
  }

  lines.push("", "  /* L2 — semantic aliases (the layer feature CSS/TSX may use) */");
  for (const [name, value] of aliasColorTokens(light)) lines.push(`  ${ALIAS_PREFIX}${name}: ${value};`);

  lines.push("", "  /* L3 — compat bridge for unprefixed names (pure redirects) */");
  for (const [name, alias] of legacyColorTokens(light)) lines.push(`  --${name}: var(${ALIAS_PREFIX}${alias});`);

  lines.push("}", "", `[data-theme="dark"] {`, `  /* L1 — full override table (${dark.metadata.id}) */`);
  for (const [name, value] of staticColorTokens(dark)) lines.push(`  ${STATIC_PREFIX}${name}: ${value};`);
  lines.push("}", "");

  return lines.join("\n");
}
