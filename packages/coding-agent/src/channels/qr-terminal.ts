/**
 * Terminal QR rendering for `zetacode channels login`.
 *
 * The workspace already ships a zero-dependency QR encoder for the collab
 * join link (`@linxiraos/pi-tui/chrome/qrcode`), so the CLI path reuses it
 * instead of adding a runtime dependency. A QR payload is rendered with
 * UTF-8 upper/lower half blocks; when the payload is an image (a data URL or
 * an image URL we cannot decode without fetching it) or the terminal is too
 * narrow, the raw payload is printed as a fallback line.
 */

import { QrCode, renderQrHalfBlocks, renderQrText } from "@linxiraos/pi-tui/chrome/qrcode";

export interface TerminalQrOptions {
	/** Terminal width in columns. When finite and too small, fall back to text. */
	columns?: number;
	/** Quiet-zone width in modules (default 4). */
	margin?: number;
	/**
	 * Wrap the symbol in black-on-white ANSI colors. Default false so tests and
	 * redirected output get plain block characters.
	 */
	color?: boolean;
}

export interface TerminalQrResult {
	/** `qr` when a symbol was produced, `fallback` when only the raw payload can be shown. */
	kind: "qr" | "fallback";
	/** The string that was encoded (or the raw payload on fallback). */
	payload: string;
	/** Rendered lines. On fallback this is exactly one line with the raw payload. */
	lines: string[];
	/** Rendered width in columns (0 on fallback). */
	width: number;
	/** Why the renderer fell back, e.g. `image-payload` or `terminal-too-narrow`. */
	reason?: string;
}

/** Whether a payload points at an image rather than carrying scannable text. */
export function isImagePayload(payload: string): boolean {
	const value = payload.trim();
	if (value === "") return false;
	if (/^data:image\//i.test(value)) return true;
	if (/^https?:\/\//i.test(value)) {
		try {
			const url = new URL(value);
			return /\.(?:png|jpe?g|gif|webp|svg|bmp)$/i.test(url.pathname);
		} catch {
			return false;
		}
	}
	return false;
}

/**
 * A QR image URL generated by a service that takes the scannable content in a
 * `data` query parameter can still be encoded locally: pull that parameter out
 * instead of fetching and decoding the image.
 */
function payloadFromImageUrl(payload: string): string | null {
	if (!/^https?:\/\//i.test(payload)) return null;
	try {
		const data = new URL(payload).searchParams.get("data");
		return data !== null && data.trim() !== "" ? data : null;
	} catch {
		return null;
	}
}

/**
 * Render one QR payload as terminal rows. The caller supplies the terminal
 * width so a narrow terminal gets the raw payload (still usable by copying
 * into a browser) instead of a clipped, unscannable symbol.
 */
export function renderTerminalQr(payload: string, options: TerminalQrOptions = {}): TerminalQrResult {
	const raw = payload.trim();
	if (raw === "") {
		return { kind: "fallback", payload, lines: [payload], width: 0, reason: "empty-payload" };
	}

	// A QR-image service that carries the scan content in `?data=` can be
	// encoded locally, before the image-URL fallback below.
	const extracted = payloadFromImageUrl(raw);
	const content = extracted ?? raw;
	if (extracted === null && isImagePayload(raw)) {
		return { kind: "fallback", payload: raw, lines: [raw], width: 0, reason: "image-payload" };
	}

	let qr: QrCode;
	try {
		qr = QrCode.encodeText(content, "M");
	} catch (error) {
		return {
			kind: "fallback",
			payload: raw,
			lines: [raw],
			width: 0,
			reason: error instanceof Error ? error.message : "encode-failed",
		};
	}

	const margin = Math.max(0, options.margin ?? 4);
	const width = qr.size + margin * 2;
	if (options.columns !== undefined && Number.isFinite(options.columns) && options.columns < width) {
		return {
			kind: "fallback",
			payload: raw,
			lines: [raw],
			width,
			reason: `terminal-too-narrow (${Math.trunc(options.columns)} columns, need ${width})`,
		};
	}

	const lines = options.color ? renderQrHalfBlocks(qr, { margin }) : renderQrText(qr, false, { margin });
	return {
		kind: "qr",
		payload: content,
		lines,
		width: lines.reduce((max, line) => Math.max(max, line.replace(/\x1b\[[0-9;]*m/g, "").length), 0),
	};
}
